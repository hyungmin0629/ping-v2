-- =====================================================================
-- 001_school_neis_office_code.sql · 학교에 시도교육청코드 추가
-- =====================================================================
-- 왜 필요한가:
--   NEIS 의 급식·시간표·학사일정 API 는 학교를 지목할 때
--   **시도교육청코드(ATPT_OFCDC_SC_CODE) + 표준학교코드(SD_SCHUL_CODE)** 를
--   한 쌍으로 요구한다. 스키마에는 표준학교코드(neis_school_code)만 있어서
--   학교 목록은 넣을 수 있어도 그 학교의 급식을 부를 수가 없다.
--
-- 왜 sido 로 유추하지 않는가:
--   시도교육청은 17개라 지역명과 대체로 1:1 이지만, 소재지와 관할 교육청이
--   다른 학교가 존재한다. 유추한 값으로 API 를 부르면 조용히 빈 결과가 온다.
--   받은 값을 그대로 저장하는 쪽이 안전하다.
--
-- 재실행해도 안전하다.
-- =====================================================================

ALTER TABLE school ADD COLUMN IF NOT EXISTS neis_office_code varchar(10);

COMMENT ON COLUMN school.neis_office_code IS
    'NEIS 시도교육청코드(ATPT_OFCDC_SC_CODE). 급식·시간표 조회에 학교코드와 함께 쓴다';
