-- 007_hint_char_per_purchase.sql · 자모 힌트마다 글자를 따로 뽑는다 (W14)
-- =====================================================================
-- 006 에서는 초성·중성·종성이 **같은 한 글자**를 가리켰다. 셋을 다 사면
-- 그 글자가 완성되는(○ㅎ○ → ○혀○ → ○형○) 구조였다.
--
-- 그걸 되돌린다. 세 힌트는 **각자 다른 글자**를 무작위로 가리킨다.
--
--     초성   ○ㅎ○
--     중성   ○○ㅣ
--     종성   ㅁ○○
--
-- 합치지 않고 셋을 나란히 보여준다. 조각을 맞추는 재미는 사는 사람 몫이고,
-- 글자를 하나로 묶으면 세 힌트가 사실상 한 글자짜리 정보가 된다 —
-- 20하트를 세 번 받고 파는 정보로는 얇다.
--
-- 그래서 글자 위치는 **투표 한 건에 하나**가 아니라 **힌트 한 건에 하나**다.
-- vote_received 에 있던 컬럼을 hint_purchase 로 옮긴다.
--
-- 재실행해도 안전하다.
-- =====================================================================

ALTER TABLE hint_purchase
    ADD COLUMN IF NOT EXISTS char_index smallint;

COMMENT ON COLUMN hint_purchase.char_index IS
    '이 자모 힌트가 가리키는 닉네임 글자 위치(0부터). 초성·중성·종성만 쓴다';

-- 006 이 vote_received 에 넣었던 컬럼. 쓰는 곳이 없어졌다.
-- my_vote_received 뷰가 이 컬럼을 붙들고 있으므로 먼저 내린다.
-- 뷰는 db/rls/hints.sql 이 새 모양으로 다시 만든다.
DROP VIEW IF EXISTS public.my_vote_received;
ALTER TABLE vote_received DROP COLUMN IF EXISTS hint_char_index;
