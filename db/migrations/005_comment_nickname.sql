-- =====================================================================
-- 005_comment_nickname.sql · 댓글도 닉네임으로 (W9)
-- =====================================================================
-- 왜 필요한가:
--   게시판을 **익명이 아니라 닉네임이 드러나는 자유게시판**으로 열기로 했다
--   ([[DECISIONS]]). 그런데 스키마는 익명 게시판 전제로 만들어져 있어
--   post_comment.anonymous_seq 가 NOT NULL 이다.
--
--   이대로 두면 두 가지가 걸린다.
--
--   1. 쓰지도 않을 익명 번호를 억지로 채워야 한다.
--   2. 더 나쁜 것 — UNIQUE (post_id, author_id, anonymous_seq) 때문에
--      **한 사람이 한 글에 댓글을 두 번 달 수 없다.** 번호를 1 로 고정하면
--      두 번째 댓글이 제약 위반으로 튕긴다. 대화가 성립하지 않는다.
--
--   nullable 로 바꾸면 둘 다 풀린다. Postgres 의 UNIQUE 는 NULL 을 서로 다른
--   값으로 보므로, 번호가 없는 댓글은 몇 개든 달린다.
--
-- 왜 컬럼을 지우지 않았나:
--   익명 게시판은 폐기가 아니라 **보류**다(재검토 조건은 [[DECISIONS]]).
--   조건이 갖춰져 익명으로 열게 되면 이 컬럼이 그대로 필요하다.
--   지금 지웠다가 다시 만들면 그 사이 댓글에는 번호를 소급할 수 없다.
--
-- 재실행해도 안전하다.
-- =====================================================================

ALTER TABLE post_comment ALTER COLUMN anonymous_seq DROP NOT NULL;

COMMENT ON COLUMN post_comment.anonymous_seq IS
    '익명 게시판용 글 안에서만 유효한 번호. 닉네임을 드러내는 자유게시판(W9)에서는 NULL 이다';
