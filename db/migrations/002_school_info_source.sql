-- =====================================================================
-- 002_school_info_source.sql · 조직이 빌려 쓸 학교를 가리킨다
-- =====================================================================
-- 왜 필요한가:
--   클로즈드 테스트 조직("코드잇 DA 14기")은 실제 학교가 아니라 급식도 시간표도
--   없다. 그렇다고 이름을 실제 학교로 바꾸면 테스터에게 낯설다.
--   표시명은 그대로 두고 **정보만 실제 학교(서울고등학교)에서 받아오기로** 했다.
--
-- 왜 neis_school_code 를 직접 넣지 않는가:
--   그 컬럼은 UNIQUE 다. 서울고등학교 행이 이미 그 코드를 갖고 있어서 같은 값을
--   조직 행에 넣을 수 없다. 억지로 옮기면 학교 목록을 다시 받을 때(--schools)
--   ON CONFLICT 가 조직 이름을 "서울고등학교"로 덮어쓴다.
--   표시용 조직과 정보 출처를 분리하는 쪽이 안전하다.
--
-- 쓰는 법:
--   급식·시간표를 부를 때 coalesce(info_school_id, id) 의 NEIS 코드를 쓴다.
--   보통 학교는 비어 있으므로 자기 자신을 가리킨다.
--
-- 재실행해도 안전하다.
-- =====================================================================

ALTER TABLE school ADD COLUMN IF NOT EXISTS info_school_id bigint REFERENCES school(id);

COMMENT ON COLUMN school.info_school_id IS
    '급식·시간표를 어느 학교에서 받아올지. 비어 있으면 자기 자신. '
    '실제 학교가 아닌 테스트 조직이 실제 학교 정보를 빌려 쓰는 데 쓴다';
