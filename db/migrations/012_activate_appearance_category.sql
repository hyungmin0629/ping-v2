-- 012_activate_appearance_category.sql · 외모·신체 카테고리를 켠다
-- =====================================================================
-- ⚠️ **실서비스에 반영되는 변경이다.** 이 마이그레이션이 Supabase 에 적용되면
--    외모·신체 질문이 실제 이용자에게 출제될 수 있게 된다.
--
-- 왜 켜나 — 신고율을 재기 위해서다. `question_category.is_sensitive` 플래그는
-- 처음부터 있었지만 민감한 질문이 하나도 없어서 **아무것도 구분하지 못했다.**
-- 실제로 얼마나 신고되는지 모르면 그 플래그도, 신고 파이프라인도 검증할 수 없다.
--
-- 무엇을 안 하나 — 질문 자체는 이 파일에서 만들지 않는다. 카테고리만 연다.
-- 어떤 문장을 낼지는 별도 판단이며, 외모 비하로 읽힐 문장은 넣지 않는다.
-- 신고 사유에 이미 `Q_APPEARANCE`('외모 비하 소지')가 있다.
--
-- 90_seed_master.sql 은 `ON CONFLICT (code) DO NOTHING` 이라 **이미 행이 있는
-- DB 에서는 아무 일도 일어나지 않는다.** 그래서 여기서 따로 UPDATE 한다.
-- 새 DB 는 시드가 처음부터 true 로 넣으므로 이 문장이 무의미하게 돈다(정상).
--
-- 재실행해도 안전하다.
-- =====================================================================

UPDATE question_category
   SET is_active = true
 WHERE code = 'APPEARANCE'
   AND is_active = false;

COMMENT ON COLUMN question_category.is_active IS
    '출제 대상인가. APPEARANCE 는 2026-08-03 에 켰다(012) — 민감 질문의 '
    '신고율을 측정하기 위해서다. 끄면 즉시 출제에서 빠진다.';
