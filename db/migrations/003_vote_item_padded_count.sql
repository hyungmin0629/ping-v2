-- =====================================================================
-- 003_vote_item_padded_count.sql · 스코프 밖에서 채운 후보 수
-- =====================================================================
-- 왜 필요한가:
--   후보가 4명이 안 될 때 스코프를 낮추던 것을, **친구 중 다른 사람으로 채우는**
--   방식으로 바꿨다. 같은 반 친구가 둘뿐이어도 "우리 반에서" 질문을 낼 수 있다.
--
--   그러면 CLASS 질문에 다른 반 후보가 섞인다. 그 사실을 기록해두지 않으면
--   정합성 검사가 이것을 결함으로 잡고("CLASS 스코프에 타반 후보"),
--   분석에서도 규칙 위반과 구분할 수 없다.
--
--   몇 명을 채웠는지까지 남긴다. "친구 구성이 얼마나 편중돼 있나"를
--   이 값으로 셀 수 있다.
--
-- 재실행해도 안전하다.
-- =====================================================================

ALTER TABLE vote_item
    ADD COLUMN IF NOT EXISTS padded_count smallint NOT NULL DEFAULT 0
    CHECK (padded_count BETWEEN 0 AND 4);

COMMENT ON COLUMN vote_item.padded_count IS
    '스코프 밖 친구로 채운 후보 수. 0 이면 전부 해당 스코프 안에서 뽑혔다';
