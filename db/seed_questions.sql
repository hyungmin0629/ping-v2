-- =====================================================================
-- 합성 데이터의 240문항은 로컬 DB 에만 있다. Supabase 는 실유저 전용이라
-- 질문도 따로 넣어야 한다.
--
-- 왜 학교 맥락인가:
--   만들려는 것이 학생용 서비스다. 실제 이용자는 성인 지인이지만, 그들이
--   확인해야 하는 것은 "학생이 쓸 때 말이 되는가"다. 성인 맥락 질문으로
--   시험하면 검증한 것이 만들려는 것과 달라진다. ([[DECISIONS]])
--
-- 무엇을 뺐나:
--   외모·신체 질문. question_category 의 APPEARANCE 는 is_active = false 다
--   — 구 서비스에서 신고 상위 5개 질문을 이 카테고리가 독점했다.
--   "제일 못하는 사람" 같은 부정형도 넣지 않았다. 지목당한 쪽이 열어볼 이유가 없고,
--   대상이 학생일수록 더 그렇다.
--
-- 스코프:
--   CLASS  = 같은 반 친구 / SCHOOL = 같은 학교 친구 / GLOBAL = 친구 전체
--   셋 다 친구가 전제다. 모르는 사람은 어떤 경우에도 후보로 뜨지 않는다.
--
-- 재실행해도 안전하다(같은 문구는 다시 넣지 않는다).
-- =====================================================================

-- 부트캠프 맥락으로 넣었던 초기 질문을 걷어낸다.
-- 이미 출제된 적이 있으면(투표 기록이 참조하면) 지우지 않고 RETIRED 로 내린다
-- — 과거 투표의 해석이 깨지면 안 되기 때문이다.
-- (친구 전체 스코프 8문항은 학교 맥락에서도 그대로 쓰므로 목록에 없다)
UPDATE question SET status = 'RETIRED'
 WHERE text IN (
        '발표를 제일 잘할 것 같은 사람은?',
        '막히는 문제를 같이 붙잡아줄 것 같은 사람은?',
        '회의 분위기를 부드럽게 만드는 사람은?',
        '마감 전날에도 침착할 것 같은 사람은?',
        '가장 늦게까지 붙잡고 있을 것 같은 사람은?',
        '회식 장소를 제일 잘 고를 것 같은 사람은?',
        '질문을 가장 편하게 할 수 있는 사람은?',
        '5년 뒤에 팀을 이끌고 있을 것 같은 사람은?',
        '제일 꼼꼼할 것 같은 사람은?',
        '처음 봤을 때 말 걸기 편했던 사람은?',
        '데이터 이야기를 밤새 할 수 있을 것 같은 사람은?',
        '무심코 던진 말이 제일 웃긴 사람은?',
        '스터디를 꾸리면 끝까지 갈 것 같은 사람은?',
        '취향이 확고해 보이는 사람은?',
        '나중에 창업하면 잘될 것 같은 사람은?');

-- 한 번도 출제되지 않은 것은 그냥 지운다(RETIRED 로 쌓아둘 이유가 없다).
DELETE FROM question q
 WHERE q.status = 'RETIRED'
   AND NOT EXISTS (SELECT 1 FROM vote_item v WHERE v.question_id = q.id);


INSERT INTO question (text, scope, category_id, status, source)
SELECT v.text, v.scope::question_scope, c.id, 'ACTIVE', 'OFFICIAL'
FROM (VALUES
    -- 같은 반에서 --------------------------------------------------
    ('우리 반에서 발표를 제일 잘하는 사람은?',         'CLASS',  'TALENT'),
    ('모르는 문제를 물어보기 편한 사람은?',            'CLASS',  'RELATIONSHIP'),
    ('수업 분위기를 밝게 만드는 사람은?',              'CLASS',  'HUMOR'),
    ('시험 기간에도 침착할 것 같은 사람은?',           'CLASS',  'PERSONALITY'),
    ('준비물을 항상 챙겨올 것 같은 사람은?',           'CLASS',  'SCHOOL_LIFE'),
    ('오늘 급식 메뉴를 제일 먼저 아는 사람은?',        'CLASS',  'SCHOOL_LIFE'),
    ('조별과제를 같이 하면 든든한 사람은?',            'CLASS',  'RELATIONSHIP'),
    ('10년 뒤가 제일 궁금한 사람은?',                  'CLASS',  'FUTURE'),

    -- 같은 학교에서 ------------------------------------------------
    ('우리 학교에서 제일 꼼꼼할 것 같은 사람은?',      'SCHOOL', 'PERSONALITY'),
    ('처음 봤는데 말 걸기 편했던 사람은?',             'SCHOOL', 'RELATIONSHIP'),
    ('좋아하는 걸 이야기할 때 제일 신나 보이는 사람은?', 'SCHOOL', 'TASTE'),
    ('무심코 던진 말이 제일 웃긴 사람은?',             'SCHOOL', 'HUMOR'),
    ('동아리를 만들면 끝까지 갈 것 같은 사람은?',      'SCHOOL', 'SCHOOL_LIFE'),
    ('노래방에서 제일 잘할 것 같은 사람은?',           'SCHOOL', 'TALENT'),
    ('나중에 선생님이 되면 잘 어울릴 것 같은 사람은?', 'SCHOOL', 'FUTURE'),
    ('힘들 때 연락하면 들어줄 것 같은 사람은?',        'SCHOOL', 'RELATIONSHIP'),

    -- 친구 전체에서 ------------------------------------------------
    ('오늘 갑자기 만나도 반가울 사람은?',              'GLOBAL', 'RELATIONSHIP'),
    ('같이 여행 가면 편할 것 같은 사람은?',            'GLOBAL', 'TASTE'),
    ('고민을 털어놓기 좋은 사람은?',                   'GLOBAL', 'PERSONALITY'),
    ('아는 게 제일 많을 것 같은 사람은?',              'GLOBAL', 'TALENT'),
    ('단톡방을 살리는 사람은?',                        'GLOBAL', 'HUMOR'),
    ('10년 뒤에도 연락하고 있을 것 같은 사람은?',      'GLOBAL', 'FUTURE'),
    ('추천해준 건 믿고 봐도 되는 사람은?',             'GLOBAL', 'TASTE'),
    ('무슨 일이든 끝까지 해낼 것 같은 사람은?',        'GLOBAL', 'PERSONALITY')
) AS v(text, scope, category_code)
JOIN question_category c ON c.code = v.category_code AND c.is_active
WHERE NOT EXISTS (SELECT 1 FROM question q WHERE q.text = v.text);
